// Builds styles.css from the shared glass kit and the plugin's own rules.
import { readFileSync, writeFileSync } from 'fs';

const kit = readFileSync('styles/apple-kit.css', 'utf8');
const own = readFileSync('styles/plugin.css', 'utf8');
writeFileSync('styles.css', `/* Generated by styles/build.mjs. Edit styles/apple-kit.css or styles/plugin.css. */\n\n${kit}\n${own}`);
